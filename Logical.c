#include<stdio.h>
int main(){
/* logical operators
   && => And
   || => Or
   !  => Not
*/
    printf("The final Ans1: %d \n",3>4 || 5>2);      // Union of false and true
    printf("The final Ans2: %d \n",3>4 && 5>2);      // Intersection of false and true
    printf("The final Ans3: %d \n", !(5>2));         // Negation of true











    return 0;
}